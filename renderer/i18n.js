  // 'auto' → closest supported language for a system locale such as "de-AT"
  function resolve(pref, systemLocale) {
    if (pref && pref !== 'auto' && S[pref]) return pref;
    const base = String(systemLocale || 'en').toLowerCase().split(/[-_]/)[0];
    return S[base] ? base : 'en';
  }

  function make(lang) {
    const dict = S[lang] || S.en;
    const t = (key, vars) => {
      let s = dict[key] ?? S.en[key] ?? key;
      if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
      return s;
    };
    const fmtDur = (sec, short) => {
      if (sec == null || !isFinite(sec)) return '—';
      sec = Math.max(0, Math.round(sec));
      const h = Math.floor(sec / 3600), m = Math.floor((sec % 3600) / 60), s = sec % 60;
      if (short) return h > 0 ? t('dur.short.h', { h, m }) : t('dur.short.m', { m });
      if (h > 0) return t('dur.h', { h, m: String(m).padStart(2, '0') });
      if (m > 0) return t('dur.m', { m, s: String(s).padStart(2, '0') });
      return t('dur.s', { s });
    };
    return { lang, locale: (LANGS[lang] || LANGS.en).locale, t, fmtDur };
  }

  return { LANGS, STRINGS: S, resolve, make };
